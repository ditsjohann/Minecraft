"""Writes docs/CONTENT.md: every item, block, bomb and scripted event in the mod, grouped like the creative tabs.

Reads the registries (ModItems.java, ModBlocks.java), the Catalog's "New" set, Events.java and the generated
language file, so run tools/generate_assets.py first if you changed names or descriptions.

    python3 tools/list_content.py
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT / "src/main/java/com/armageddon"
LANG = json.loads((ROOT / "src/main/resources/assets/armageddon/lang/en_us.json").read_text())

TIERS = ["FUN", "UNCOMMON", "RARE", "EPIC", "LEGENDARY", "MYTHIC", "CELESTIAL", "CITY_DESTRUCTION", "WORLD_DESTRUCTION"]
TIER_NAME = {t: t.replace("_", " ").title() for t in TIERS}
WEAPON_CLASSES = {
    "LauncherItem", "CallerItem", "TargetingItem", "PlasmaRifleItem", "RailgunItem", "MinigunItem", "FlamethrowerItem",
    "ArcThrowerItem", "GravityHammerItem", "PlasmaBladeItem", "DubstepGunItem", "DeathRayItem", "GatlingItem", "AirhornItem",
    "TetherItem", "AntimatterLanceItem", "RiftBorerItem", "ResonanceCannonItem", "SunlanceItem", "WorldsplitterItem",
    "JudgmentEngineItem", "SwordItem",
}
AMMO = {"mini_nuke", "rocket", "plasma_cell", "railgun_slug", "bullet_belt", "fuel_canister", "cryo_canister", "solar_cell"}


def registry(path, kind):
    src = path.read_text()
    out = []
    for m in re.finditer(r"public static final [\w<>?, ]+ (\w+)\s*=(.*?);\n", src, re.S):
        const, body = m.groups()
        idm = re.search(r'\b(?:register|bomb|block|armor)\w*\("([a-z0-9_]+)"', body)
        if not idm:
            continue
        cls = re.search(r"new (?:[\w.]+\.)?(\w+)\(", body)
        tier = re.search(r"Tier\.([A-Z_]+)", body)
        bt = re.search(r"BombType\.([A-Z_0-9]+)", body)
        out.append(dict(id=idm.group(1), const=const, kind=kind, cls=cls.group(1) if cls else "", tier=tier.group(1) if tier else "",
                        bomb=bt.group(1) if "bomb(" in body and bt else None, armor="armor(" in body))
    return out


def newest():
    src = (JAVA / "registry/Catalog.java").read_text()
    block = src[src.index("NEWEST = Set.of("):]
    block = block[:block.index(";")]
    return set(re.findall(r"BombType\.([A-Z_0-9]+)", block))


def name(r):
    return LANG.get(f"{r['kind']}.armageddon.{r['id']}", r["id"])


def desc(r):
    key = f"{r['kind']}.armageddon.{r['id']}"
    return LANG.get(key + ".desc") or LANG.get(key + ".tooltip") or ""


def category(r, new):
    if r["kind"] == "block":
        if r["bomb"]:
            if r["bomb"] in new:
                return "New"
            return "Cataclysms" if r["tier"] in TIERS[6:] else "Bombs"
        return "Gear & Materials"
    if r["cls"] == "DetonatorItem":
        return "Bombs"
    if r["cls"] in ("GrenadeItem", "BoomerangItem"):
        return "Explosives"
    if r["cls"] in WEAPON_CLASSES or r["id"] in ("helix_disruptor", "graviton_lance", "sunfall_mortar", "halo_cutter",
                                                  "hyperbeam_raygun", "obliterator"):
        return "Weapons"
    return "Gear & Materials"


def clean(s):
    return " ".join(s.replace("|", "/").split())


def main():
    rows = registry(JAVA / "registry/ModItems.java", "item") + registry(JAVA / "registry/ModBlocks.java", "block")
    new = newest()
    events = re.findall(r'EVENTS\.put\("([a-z0-9_]+)"', (JAVA / "event/Events.java").read_text())
    groups = defaultdict(list)
    for r in rows:
        groups[category(r, new)].append(r)

    order = ["Weapons", "Explosives", "Bombs", "Cataclysms", "New", "Gear & Materials"]
    blurb = {
        "Weapons": "Guns, launchers, melee weapons, orbital designators and callers.",
        "Explosives": "Thrown grenades and throwables.",
        "Bombs": "Placeable warheads below Celestial tier (plus the Remote Detonator).",
        "Cataclysms": "Celestial, City Destruction and World Destruction bombs (gated by `armageddonAllowCelestial`).",
        "New": "The most recent bombs, kept in the \"Armageddon: New\" creative tab for now (`Catalog.NEWEST`).",
        "Gear & Materials": "Armour, tools, gadgets, ammo, crafting materials, ores and building blocks.",
    }
    tiered = sum(1 for r in rows if r["tier"])
    lines = [
        "# Armageddon Arsenal: full content list",
        "",
        "Generated by `python3 tools/list_content.py` from the registries and the language file. Do not edit by hand.",
        "",
        f"**{len(rows)} registered items and blocks**: {sum(1 for r in rows if r['bomb'])} bombs, "
        f"{len(groups['Weapons'])} weapons, {len(groups['Explosives'])} explosives, {tiered} with an arsenal tier. "
        f"**{len(events)} scripted events** can be started with `/armageddon event <id>`.",
        "",
        "## Count by tier",
        "",
        "| Tier | Count |",
        "| --- | ---: |",
    ]
    for t in TIERS:
        lines.append(f"| {TIER_NAME[t]} | {sum(1 for r in rows if r['tier'] == t)} |")
    lines.append(f"| (no tier: materials, ammo, tools, armour) | {sum(1 for r in rows if not r['tier'])} |")
    lines.append("")

    for cat in order:
        items = groups[cat]
        items.sort(key=lambda r: (TIERS.index(r["tier"]) if r["tier"] else -1, name(r).lower()))
        lines += [f"## {cat} ({len(items)})", "", blurb[cat], "", "| Name | Id | Tier | What it does |", "| --- | --- | --- | --- |"]
        for r in items:
            lines.append(f"| **{clean(name(r))}** | `{r['id']}` | {TIER_NAME.get(r['tier'], '-')} | {clean(desc(r))} |")
        lines.append("")

    lines += ["## Scripted event ids", "", "Use with `/armageddon event <id>` to start any of them at your feet without crafting.", ""]
    lines.append(", ".join(f"`{e}`" for e in sorted(events)))
    lines.append("")
    (ROOT / "docs/CONTENT.md").write_text("\n".join(lines))
    print(f"docs/CONTENT.md: {len(rows)} entries, {len(events)} events")


if __name__ == "__main__":
    main()
